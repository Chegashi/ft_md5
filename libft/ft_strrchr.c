#include "libft.h"

char	*ft_strrchr(const char *s, int c)
{
	int	len;

	len = ft_strlen(s);
	if (s[len] == '\0' && (char)c == '\0')
		return ((char *)s + len);
	while (len)
	{
		if (s[len] == (char)c)
			return ((char *)s + len);
		else
			len--;
	}
	if (*s == (char)c)
		return ((char *)s);
	return (0);
}
