#include "libft.h"

void	*ft_memmove(void *dst, const void *src, size_t len)
{
	unsigned char	*s;
	unsigned char	*d;

	s = (unsigned char *)src;
	d = (unsigned char *)dst;
	if (d == s)
		return (dst);
	if (d > s && d < s + len)
	{
		while (len--)
			ft_memset((d + len), (char)(*(s + len)), 1);
		ft_memset(d, *s, 1);
	}
	else
		ft_memcpy(d, s, len);
	return (dst);
}
